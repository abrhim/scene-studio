// Builds dem.js from sources/dem-grid.json: the heights the base reads synchronously (a script tag, so plug-ins can
// call groundY in init, and the page works from file:// too).
//   fine:   full-resolution posts (int16 metres) around the land tile, with a 1200 m real margin (the inner skirt) and
//           3 extra posts for the bicubic stencil
//   coarse: the whole DEM averaged over 4 x 4 posts, for the outer skirt out to the haze
// Run from the scene folder: node tools/build-dem.mjs
import fs from 'node:fs';
const dem = JSON.parse(fs.readFileSync('sources/dem-grid.json', 'utf8'));
const meta = JSON.parse(fs.readFileSync('sources/dem-meta.json', 'utf8'));
const W = dem.width, H = dem.height, D = dem.data;
const MX = meta.metres_per_px_x, MY = meta.metres_per_px_y;
const O = [313, 262];               // Hill 689 summit post: the origin
const B6 = [284, 298.5];            // battle-hill summit (rows 298 and 299 are both 610 m)
// the tile: 3000 x 2610 m real, centred between the two summits (index.html LAND.tile must match)
const cx = ((O[0] + B6[0]) / 2 - O[0]) * MX, cz = ((O[1] + B6[1]) / 2 - O[1]) * MY;
const tx0 = cx - 1500 - 1200, tx1 = cx + 1500 + 1200, tz0 = cz - 1305 - 1200, tz1 = cz + 1305 + 1200;
const c0 = Math.max(0, Math.floor(O[0] + tx0 / MX) - 3), c1 = Math.min(W - 1, Math.ceil(O[0] + tx1 / MX) + 3);
const r0 = Math.max(0, Math.floor(O[1] + tz0 / MY) - 3), r1 = Math.min(H - 1, Math.ceil(O[1] + tz1 / MY) + 3);
const fw = c1 - c0 + 1, fh = r1 - r0 + 1;
const fine = new Int16Array(fw * fh);
for (let r = 0; r < fh; r++) for (let c = 0; c < fw; c++) fine[r * fw + c] = D[(r + r0) * W + c + c0];
const S = 4, cw = Math.ceil(W / S), ch = Math.ceil(H / S);
const coarse = new Int16Array(cw * ch);
for (let r = 0; r < ch; r++) for (let c = 0; c < cw; c++) {
  let s = 0, n = 0;
  for (let j = 0; j < S; j++) for (let i = 0; i < S; i++) { const rr = r * S + j, cc = c * S + i; if (rr < H && cc < W) { s += D[rr * W + cc]; n++; } }
  coarse[r * cw + c] = Math.round(s / n);
}
const b64 = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
const out = `// dem.js: generated by tools/build-dem.mjs from sources/dem-grid.json (Copernicus GLO-30). Do not edit by hand.
// Heights are int16 metres (EGM2008), little-endian, row-major, north row first. Pixel centres; px (313, 262) is the
// Hill 689 summit (691 m), the scene's origin.
window.DEM = ${JSON.stringify({
  source: meta.source, width: W, height: H, mx: MX, my: MY, origin: O,
  fine: { c0, r0, w: fw, h: fh },
  coarse: { step: S, w: cw, h: ch },
})};
window.DEM.fine.b64 = '${b64(fine)}';
window.DEM.coarse.b64 = '${b64(coarse)}';
`;
fs.writeFileSync('dem.js', out);
console.log('fine', fw, 'x', fh, 'from', c0, r0, ' coarse', cw, 'x', ch, ' bytes', out.length);
